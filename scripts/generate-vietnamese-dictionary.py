#!/usr/bin/env python3
"""Generate MKey's lookup table from pinned, licensed hunspell-vi word lists.

MKey modification: union both tone styles, normalize case/NFC, keep syllables,
and encode each letter as (ASCII base, shape*6+tone). No upstream code is run.
"""
import argparse
import hashlib
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'third_party/hunspell-vi'
OUTPUT = ROOT / 'Sources/Engine/VietnameseDictionaryData.h'
HASHES = {
    'vi-DauCu.dic': '50b23ff20ea83ad886e2ff166220d53b307784c9870fb447341e0f298f0e5588',
    'vi-DauMoi.dic': 'a075773a27729713a1f5853404c7aafbb78e9056a12ccd729c19622953723143',
}
VOWELS = 'aăâeêioôơuưyáàảãạắằẳẵặấầẩẫậéèẻẽẹếềểễệíìỉĩịóòỏõọốồổỗộớờởỡợúùủũụứừửữựýỳỷỹỵ'
# This only filters source entries; it never synthesizes or corrects a word.
SHAPE = re.compile(r'(?:ngh|ng|gh|gi|kh|ph|th|ch|tr|nh|qu|[bcdđghklmnprstvx])?[' +
                   VOWELS + r']{1,3}(?:ch|ng|nh|[ckmnpt])?')
TONES = {'\u0301': 1, '\u0300': 2, '\u0309': 3, '\u0303': 4, '\u0323': 5}
SHAPES = {'\u0302': 1, '\u0306': 2, '\u031b': 2}


def encode(word):
    result = ''
    for letter in word:
        if letter == 'đ':
            base, shape, tone = 'd', 1, 0
        else:
            parts = unicodedata.normalize('NFD', letter)
            base, shape, tone = parts[0], 0, 0
            for mark in parts[1:]:
                if mark in SHAPES:
                    shape = SHAPES[mark]
                elif mark in TONES:
                    tone = TONES[mark]
                else:
                    raise ValueError(f'Unsupported mark: {letter!r}')
        if not 'a' <= base <= 'z':
            raise ValueError(f'Unsupported base: {letter!r}')
        result += base + chr(ord('a') + shape * 6 + tone)
    return result


def generate():
    words = set()
    for name, expected in HASHES.items():
        data = (SOURCE / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError(f'Source hash mismatch: {name}')
        lines = data.decode('utf-8-sig').splitlines()
        if lines[0] != str(len(lines) - 1):
            raise ValueError(f'Entry count mismatch: {name}')
        words.update(unicodedata.normalize('NFC', word.strip()).lower() for word in lines[1:])
    words = sorted(word for word in words if SHAPE.fullmatch(word))
    normalized = ('\n'.join(words) + '\n').encode('utf-8')
    if len(words) != 6678 or hashlib.sha256(normalized).hexdigest() != \
            'c99eb94c7d0305bc40e4397f45649abbc83087de9666fa7de4b4f6d29351a49d':
        raise ValueError('Unexpected derived dictionary; review the source/normalization')
    entries = sorted((encode(word), word) for word in words)
    if len({key for key, _ in entries}) != len(entries):
        raise ValueError('Dictionary encoding collision')
    lines = [
        '// Generated by scripts/generate-vietnamese-dictionary.py; do not edit.',
        '// Data: 1ec5/hunspell-vi@39cc647f0cf3bdfc579980a2c3aac3f6f4203fe6, GPL-3.0-or-later.',
        '// See VietnameseDictionary-NOTICE.txt and third_party/hunspell-vi/.',
        f'static const size_t kMaxWordLength = {max(map(len, words))};',
        'static const char* const kVietnameseWords[] = {',
    ]
    lines += [f'    "{key}", // {word}' for key, word in entries]
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in table differs')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            parser.exit(1, 'Vietnamese dictionary table is stale; regenerate it.\n')
    else:
        OUTPUT.write_text(generated)
    print('Vietnamese dictionary: 6678 entries, source hashes and generated table verified')
